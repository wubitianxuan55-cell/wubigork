const cadTakeoffBody = `你收到了 gaea CAD 识图工具产出的图纸识别数据（对话消息中带【CAD 图纸算量】前缀）。
本技能定义从识别数据到算量表与组价的工作流与纪律。开工前先通读。

## 数据口径（识图工具的输出语义）

- 符号统计：block=图上块引用的原始块名；name=邻近文字众数的自动命名
  （confidence=置信度 0~1，name 为空=未能自动命名）；count=图上实例数
  ——块引用计数，精确值，不是估算；perSheet=分布（图框序号→数量）。
- 图层线长：length=该图层线/多段线的几何长度合计（mm 图纸即毫米）。
  几何长度≠施工量：配管预留、导线弛度、损耗等系数由你按工程惯例给出，
  且必须明示系数与依据，不得静默乘入。
- 图上文字：矢量层提取的图纸文字（设计说明、表格外文字等），是口径
  与做法的权威来源。

## 工作流

1. 待确认清单先行：未命名符号与低置信度（confidence<0.8）项，先列出
   你的推断名称与依据（块名/图上文字/所在图框），请用户确认后再计入算量。
2. 算量表：同名符号归并；单位按专业惯例（个/套/台/米）；线长类给
   「几何长度×系数=工程量」；每行附数据来源（块名或图层），保证可回溯。
3. 组价：用你已有的造价能力（清单/定额库检索、组价工具）匹配子目；
   宁缺勿误——匹配不上的行如实标「未匹配」，绝不编造定额号或价格；
   缺口径时向用户要，不猜。
4. 输出三段：算量表（markdown 表：序号/名称/单位/数量/依据）→ 组价结果
   → 待确认事项。落库/导出只在用户确认后进行（走既有造价工具的确认语义）。

## 铁律

- 数量只来自工具数据（块计数/线长/图上文字），不得目测补数或四舍五入凑整。
- 未确认的命名与系数不得静默采用；用户未回复确认前，算量表标注「待确认」。
- 图纸上没有的量不虚构；缺项列「待补充」并说明需要哪张图/哪个表。
- 结论与数字出现修改时，明确指出改了什么、依据是什么。`
