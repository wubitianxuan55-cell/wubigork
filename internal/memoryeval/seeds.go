func StorySeeds() []memory.Memory {
	seeds := make([]memory.Memory, 0, len(storyTargets)+len(storyFillerTopics))
	seeds = append(seeds, storyTargets...)
	for i, topic := range storyFillerTopics {
		seeds = append(seeds, memory.Memory{
			ID:         fmt.Sprintf("第%d章·支线", storyFillerChapters[i]),
			ChapterNum: storyFillerChapters[i],
			Category:   "event",
			Text:       "本章为市井支线：" + topic + "。众人各自歇息，并无大事。",
		})
	}
	return seeds
}

