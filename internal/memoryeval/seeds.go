// WorkSeeds work 域种子语料（目标 + 陪衬），docs[i].ID == i ↔ labels[i]。
func WorkSeeds() ([]bm25.Doc, []string) {
	entries := append(append([]workEntry{}, workTargets...), workFillers...)
	docs := make([]bm25.Doc, 0, len(entries))
	labels := make([]string, 0, len(entries))
	for i, e := range entries {
		docs = append(docs, bm25.Doc{ID: i, Text: e.label + "：" + e.text})
		labels = append(labels, e.label)
	}
	return docs, labels
}

