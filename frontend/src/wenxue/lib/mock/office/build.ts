export function buildOffice(s: MakeMockState): OfficeMethods {
  if (s.scenario !== "wenxue" && s.scenario !== "library") {
    return { ...officeMethods, ...xlsxMethods } as OfficeMethods;
  }
  return {
    ...officeMethods,
    ...xlsxMethods,
    async ListDir(rel: string) {
      const key = rel.replaceAll("\\", "/").replace(/\/+$/, "");
      const names = wenxueDirectories[key];
      if (!names) return [];
      return names.map((name) => ({
        name,
        isDir: Object.hasOwn(wenxueDirectories, key ? `${key}/${name}` : name),
        size: wenxueFiles[key ? `${key}/${name}` : name]?.length ?? 0,
      }));
    },
    async Preview(rel: string) {
      const body = wenxueFiles[rel];
      if (!body) {
        return {
          path: rel,
          name: rel.split("/").pop() ?? rel,
          ext: ".md",
          size: 0,
          kind: "markdown" as const,
          body: "# 草稿\n\n浏览器文学样例只展示定稿与设定。",
          dataUrl: "",
          error: "",
        };
      }
      return {
        path: rel,
        name: rel.split("/").pop() ?? rel,
        ext: ".md",
        size: body.length,
        kind: "markdown" as const,
        body,
        dataUrl: "",
        error: "",
        mtimeMs: 1_790_000_000_000 + body.length,
      };
    },
  } as OfficeMethods;
}
